//  قائمة الجوال — Hamburger Menu
// ====================================================
(function initMobileMenu() {
    const menuToggle = document.getElementById('mobile-menu-toggle');
    const navLinks   = document.querySelector('.nav-links');
    const navOverlay = document.getElementById('nav-overlay');
    const menuIcon   = document.getElementById('menu-icon');

    if (!menuToggle || !navLinks) return;

    function openMenu() {
        navLinks.classList.add('mobile-open');
        if (navOverlay) navOverlay.classList.add('visible');
        if (menuIcon) { menuIcon.classList.remove('fa-bars'); menuIcon.classList.add('fa-xmark'); }
        document.body.style.overflow = 'hidden';
    }

    function closeMenu() {
        navLinks.classList.remove('mobile-open');
        if (navOverlay) navOverlay.classList.remove('visible');
        if (menuIcon) { menuIcon.classList.remove('fa-xmark'); menuIcon.classList.add('fa-bars'); }
        document.body.style.overflow = '';
    }

    menuToggle.addEventListener('click', () => {
        navLinks.classList.contains('mobile-open') ? closeMenu() : openMenu();
    });

    if (navOverlay) navOverlay.addEventListener('click', closeMenu);

    navLinks.querySelectorAll('a').forEach(link => {
        link.addEventListener('click', closeMenu);
    });
})();

