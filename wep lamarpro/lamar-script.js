async function showLbSlide() {
    const src = lbImages[lbIndex];
    const img = document.getElementById('lb-img');
    const vid = document.getElementById('lb-video');
    document.getElementById('lb-counter').textContent = `${lbIndex + 1} / ${lbImages.length}`;

    let resolvedSrc = src;
    let isVideo = false;

    if (src.startsWith('idb://')) {
        const key = src.slice(6);
        if (!idbURLCache[key]) {
            const blob = await MediaIDB.get(key).catch(() => null);
            if (blob) {
                isVideo = blob.type.startsWith('video/');
                idbURLCache[key]            = URL.createObjectURL(blob);
                idbURLCache[key + '_isVid'] = isVideo;
            }
        } else {
            isVideo = idbURLCache[key + '_isVid'] || false;
        }
        resolvedSrc = idbURLCache[key] || '';
    } else {
        isVideo = resolvedSrc.startsWith('data:video') || /\.(mp4|webm|ogg)$/i.test(resolvedSrc);
    }

    if (isVideo) {
        img.style.display = 'none'; vid.style.display = 'block';
        vid.src = resolvedSrc; vid.load();
    } else {
        vid.pause(); vid.style.display = 'none'; vid.src = '';
        img.style.display = 'block'; img.src = resolvedSrc;
    }

    // thumbnails
    document.getElementById('lb-thumbs').innerHTML = lbImages.map((s, i) => {
        const thumbSrc = s.startsWith('idb://') ? (idbURLCache[s.slice(6)] || '') : s;
        return `<div class="lb-thumb ${i === lbIndex ? 'active' : ''}" onclick="lbJump(${i})">
            <img src="${thumbSrc}" alt=""></div>`;
    }).join('');

    // prev/next visibility
    document.querySelector('.lb-prev').style.display = lbImages.length > 1 ? '' : 'none';
    document.querySelector('.lb-next').style.display = lbImages.length > 1 ? '' : 'none';
}

function lbJump(i) { lbIndex = i; showLbSlide(); }

