// ====================================================
const contactFormEl = document.getElementById('contact-form');
if (contactFormEl) {
    contactFormEl.addEventListener('submit', async function (e) {
        e.preventDefault();
        const submitBtn  = contactFormEl.querySelector('.form-submit-btn');
        const submitText = document.getElementById('form-submit-text');
        const origText   = submitText ? submitText.textContent : '';
        const lang       = document.documentElement.getAttribute('lang') || 'ar';

        const name    = document.getElementById('form-name').value.trim();
        const email   = document.getElementById('form-email').value.trim();
        const phone   = (document.getElementById('form-phone') || {value:''}).value.trim();
        const subject = document.getElementById('form-subject').value.trim();
        const message = document.getElementById('form-message').value.trim();

        if (!name || !email || !message) return;

        if (submitBtn) submitBtn.disabled = true;
        if (submitText) submitText.textContent = lang === 'ar' ? 'جارٍ الإرسال...' : 'Sending...';

        try {
            await fetch('api/save-contact.php', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ name, email, phone, subject, message })
            });
        } catch (_) {}

        contactFormEl.reset();
        if (submitBtn) submitBtn.disabled = false;
        if (submitText) submitText.textContent = origText;

        const successMsg = document.createElement('div');
        successMsg.className = 'contact-success-msg';
        successMsg.innerHTML = lang === 'ar'
            ? '<i class="fa-solid fa-circle-check"></i> تم إرسال رسالتك بنجاح، سنتواصل معك قريباً'
            : '<i class="fa-solid fa-circle-check"></i> Your message has been sent successfully, we\'ll be in touch soon';

        contactFormEl.style.display = 'none';
        contactFormEl.parentNode.insertBefore(successMsg, contactFormEl.nextSibling);
        setTimeout(() => {
            successMsg.remove();
            contactFormEl.style.display = '';
        }, 5000);
    });
}
